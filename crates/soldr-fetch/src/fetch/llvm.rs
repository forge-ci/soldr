/// Ensure an LLVM toolchain (clang, clang-cl, lld-link, llvm-lib, …)
/// is available for cross-compile lanes that need it. Returns the
/// directory holding the binaries so the caller can prepend it to
/// `PATH` on the child cargo and set `CC_<triple>` / `LD_<triple>` /
/// `AR_<triple>` to absolute paths inside it.
///
/// On hosts not in the managed support matrix (see `LLVM_ASSETS`),
/// returns `SoldrError::UnsupportedPlatform`. The caller should gate
/// this bootstrap behind the same target-triple check it uses to
/// decide whether the binaries are needed at all — non-cross builds
/// never reach the error path.
pub async fn ensure_llvm_toolchain(paths: &SoldrPaths) -> Result<PathBuf, SoldrError> {
    if let Some(dir) = llvm_dir_from_env_var() {
        return Ok(dir);
    }
    fetch_managed_llvm(paths).await
}

fn llvm_dir_from_env_var() -> Option<PathBuf> {
    let value = std::env::var_os(LLVM_DIR_ENV_VAR)?;
    let p = PathBuf::from(value);
    if p.is_dir() {
        Some(p)
    } else {
        None
    }
}

/// Look up the asset descriptor for the running host. Returns `None`
/// on unsupported hosts (today: macOS — see module doc-comment).
fn host_llvm_asset() -> Option<&'static LlvmAsset> {
    let triple = host_triple_for_llvm()?;
    LLVM_ASSETS
        .iter()
        .find(|(t, _)| *t == triple)
        .map(|(_, asset)| asset)
}

/// Map (arch, os) to the rustc-style triple keys used in `LLVM_ASSETS`.
/// Kept separate from `core::TargetTriple` because (a) we resolve the
/// host through the facts facade, (b) we don't need rustc's
/// MSVC-vs-GNU env discrimination on Windows (only x86_64-msvc is
/// supported today).
fn host_triple_for_llvm() -> Option<&'static str> {
    use crate::platform::host::facts::{arch, libc, os, HostArch, HostLibc, HostOs};

    match (os(), arch(), libc()) {
        (HostOs::Linux, HostArch::X86_64, HostLibc::Gnu) => Some("x86_64-unknown-linux-gnu"),
        (HostOs::Linux, HostArch::Aarch64, HostLibc::Gnu) => Some("aarch64-unknown-linux-gnu"),
        (HostOs::Windows, HostArch::X86_64, _) => Some("x86_64-pc-windows-msvc"),
        _ => None,
    }
}

/// Does this host have a managed LLVM asset?
pub(super) fn host_has_managed_llvm() -> bool {
    host_llvm_asset().is_some()
}

pub(super) fn unsupported_host_error() -> SoldrError {
    SoldrError::UnsupportedPlatform(format!(
        "managed LLVM toolchain not available for host arch={} os={} (set {LLVM_DIR_ENV_VAR} to an existing LLVM bin dir, or extend LLVM_ASSETS)",
        std::env::consts::ARCH,
        std::env::consts::OS,
    ))
}

async fn fetch_managed_llvm(paths: &SoldrPaths) -> Result<PathBuf, SoldrError> {
    let Some(asset) = host_llvm_asset() else {
        return Err(unsupported_host_error());
    };

    paths.ensure_dirs()?;
    let install_dir = super::llvm_background::managed_llvm_install_dir(paths);
    let bin_dir = super::llvm_background::managed_llvm_bin_dir(paths);
    let stamp = install_dir.join(".complete");

    // Lock-free fast path: a fully stamped install needs no repair.
    if stamp.is_file() && bin_dir.is_dir() {
        let stamped = std::fs::read_to_string(&stamp).unwrap_or_default();
        if stamped.contains(STAMP_EXEC_MARKER) && stamped.contains(STAMP_HOST_LIBS_MARKER) {
            return Ok(bin_dir);
        }
    }

    // soldr#3801: one process at a time may repair, download, extract and
    // stamp. A concurrent caller (the front door's background fetch, a
    // linking wrapper, another build) blocks here, then finds `.complete`.
    let _lock = super::llvm_background::lock_install(&install_dir).await?;
    install_locked(paths, asset, &install_dir, &bin_dir, &stamp).await
}

/// The body of [`fetch_managed_llvm`] that must run under the install lock.
async fn install_locked(
    paths: &SoldrPaths,
    asset: &LlvmAsset,
    install_dir: &Path,
    bin_dir: &Path,
    stamp: &Path,
) -> Result<PathBuf, SoldrError> {
    if stamp.is_file() && bin_dir.is_dir() {
        // An install stamped before exec bits were restored (linux-arm64
        // archive, soldr#3505) is repaired in place instead of re-fetched.
        let stamped = std::fs::read_to_string(stamp).unwrap_or_default();
        let has_exec = stamped.contains(STAMP_EXEC_MARKER);
        let has_libs = stamped.contains(STAMP_HOST_LIBS_MARKER);
        if !has_exec {
            restore_bin_exec_bits(bin_dir)?;
        }
        // soldr#3774: an install from before the host-libs overlay is
        // completed in place, too.
        let libs_done = has_libs || complete_host_libs(paths, bin_dir).await?;
        if !has_exec || libs_done != has_libs {
            write_stamp(stamp, libs_done)?;
        }
        return Ok(bin_dir.to_path_buf());
    }

    let entry = catalogue_entry_for_asset(asset).await?;
    let resolved_url = manifest_lookup::resolved_download_label(&entry);
    eprintln!(
        "soldr: fetching LLVM v{MANAGED_LLVM_VERSION} ({}) from {resolved_url}...",
        asset.plat_arch,
    );

    let downloaded = manifest_lookup::materialize_catalogue_entry(paths, &entry).await?;

    // Integrity check is mandatory — the upstream archive is large
    // (~95 MiB) and a tampered blob would silently install a hostile
    // toolchain. Match the apple_sdk policy: sha256 mismatch is a hard
    // refuse-to-extract error regardless of `SOLDR_TRUST_MODE`.
    let digest = downloaded.sha256();
    if digest != asset.sha256 {
        return Err(SoldrError::Other(format!(
            "LLVM sha256 mismatch: expected {expected}, got {digest} \
             (upstream archive at {url} may have been replaced — refusing to extract)",
            expected = asset.sha256,
            url = asset.url,
        )));
    }
    eprintln!(
        "soldr: trust: verified LLVM v{MANAGED_LLVM_VERSION} {} sha256={digest}",
        asset.plat_arch,
    );

    // soldr#4295: extract, overlay and stamp a sibling staging directory, then
    // rename the finished tree into place. The canonical name never holds a
    // partial tree, and a leftover there is replaced instead of failing.
    let staged = stage_llvm_tree(downloaded.path(), install_dir)?;
    let staged_bin = staged.path().join("hardlinked").join("bin");
    let libs_done = complete_host_libs(paths, &staged_bin).await?;
    write_stamp(&staged.path().join(".complete"), libs_done)?;
    promote_llvm_tree(staged, install_dir)?;
    debug_assert!(stamp.is_file());
    eprintln!("soldr: extracted LLVM to {}", install_dir.display());
    Ok(bin_dir.to_path_buf())
}

/// Attach the operation and path to an IO error (soldr#4295: a bare
/// `File exists (os error 17)` named nothing).
fn io_at<'a>(op: &'static str, path: &'a Path) -> impl FnOnce(std::io::Error) -> SoldrError + 'a {
    move |error| {
        SoldrError::Io(std::io::Error::new(
            error.kind(),
            format!("{op} {}: {error}", path.display()),
        ))
    }
}

/// A stamped install whose `bin` directory exists: nothing to replace.
fn llvm_tree_complete(install_dir: &Path) -> bool {
    install_dir.join(".complete").is_file() && install_dir.join("hardlinked").join("bin").is_dir()
}

/// Extract the verified LLVM archive into a fresh sibling of `install_dir`
/// (same filesystem, so the final rename is atomic) and restore exec bits.
fn stage_llvm_tree(archive: &Path, install_dir: &Path) -> Result<tempfile::TempDir, SoldrError> {
    let parent = install_dir
        .parent()
        .ok_or_else(|| SoldrError::Archive("LLVM install path has no parent".into()))?;
    std::fs::create_dir_all(parent).map_err(io_at("create", parent))?;
    let staged = tempfile::Builder::new()
        .prefix(".llvm-staging-")
        .tempdir_in(parent)
        .map_err(io_at("create staging dir in", parent))?;
    let file = std::fs::File::open(archive).map_err(io_at("open", archive))?;
    extract_tar_zst_tree(file, staged.path())?;
    let bin_dir = staged.path().join("hardlinked").join("bin");
    if !bin_dir.is_dir() {
        return Err(SoldrError::Archive(format!(
            "LLVM extract did not produce expected directory {}",
            bin_dir.display()
        )));
    }
    restore_bin_exec_bits(&bin_dir)?;
    Ok(staged)
}

/// Move whatever sits at `path` (a stale or partial tree, a file, a dangling
/// link) out of the way. A real directory is renamed aside first so the
/// canonical name frees up at once, then deleted best-effort.
fn clear_install_path(path: &Path) -> Result<(), SoldrError> {
    let meta = match std::fs::symlink_metadata(path) {
        Ok(meta) => meta,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(io_at("inspect", path)(error)),
    };
    let result = if crate::platform::fs::links::is_link_or_reparse(&meta) {
        crate::platform::fs::links::remove(path)
    } else if meta.is_dir() {
        let nonce = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|duration| duration.as_nanos())
            .unwrap_or_default();
        let mut aside = path.as_os_str().to_owned();
        aside.push(format!(".stale-{}-{nonce}", std::process::id()));
        let aside = PathBuf::from(aside);
        std::fs::rename(path, &aside).map(|()| {
            let _ = std::fs::remove_dir_all(&aside);
        })
    } else {
        std::fs::remove_file(path)
    };
    match result {
        Ok(()) => Ok(()),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(io_at("remove stale", path)(error)),
    }
}

/// Rename a finished staging tree to `install_dir`. If something is already
/// there (EEXIST/ENOTEMPTY/ENOTDIR, or Windows' access denied): accept it when
/// it is a complete stamped install (another installer won), otherwise
/// replace it and retry.
fn promote_llvm_tree(staged: tempfile::TempDir, install_dir: &Path) -> Result<(), SoldrError> {
    const ATTEMPTS: usize = 5;
    let staged = staged.keep();
    let mut last_error = None;
    for _ in 0..ATTEMPTS {
        match std::fs::rename(&staged, install_dir) {
            Ok(()) => return Ok(()),
            Err(error) if std::fs::symlink_metadata(install_dir).is_ok() => {
                if llvm_tree_complete(install_dir) {
                    let _ = std::fs::remove_dir_all(&staged);
                    return Ok(());
                }
                last_error = Some(error);
                if let Err(clear) = clear_install_path(install_dir) {
                    let _ = std::fs::remove_dir_all(&staged);
                    return Err(clear);
                }
            }
            Err(error) => {
                let _ = std::fs::remove_dir_all(&staged);
                return Err(io_at("rename staged LLVM into", install_dir)(error));
            }
        }
    }
    let _ = std::fs::remove_dir_all(&staged);
    Err(io_at("rename staged LLVM into", install_dir)(
        last_error.unwrap_or_else(|| std::io::Error::other("install path kept reappearing")),
    ))
}

/// Stage, stamp and promote a tree without the host-libs overlay (tests).
#[cfg(test)]
fn place_llvm_tree(archive: &Path, install_dir: &Path) -> Result<(), SoldrError> {
    let staged = stage_llvm_tree(archive, install_dir)?;
    write_stamp(&staged.path().join(".complete"), true)?;
    promote_llvm_tree(staged, install_dir)
}

async fn catalogue_entry_for_asset(asset: &LlvmAsset) -> Result<ManifestEntry, SoldrError> {
    // soldr#2951: `get_or_fetch` hands back an `Arc`, which needs a binding
    // before it can be reborrowed as the `&ManifestIndex` parameter.
    let index = manifest_lookup::get_or_fetch().await;
    catalogue_entry_from_index(&index, asset)
}

fn catalogue_entry_from_index(
    index: &ManifestIndex,
    asset: &LlvmAsset,
) -> Result<ManifestEntry, SoldrError> {
    let source_path = asset
        .url
        .split_once("/assets/")
        .map(|(_, path)| path)
        .ok_or_else(|| SoldrError::Other("managed LLVM identity has no assets path".into()))?;
    let asset_name = source_path
        .rsplit('/')
        .next()
        .ok_or_else(|| SoldrError::Other("managed LLVM identity has no asset name".into()))?;
    if index.source != CatalogueSource::CanonicalV2 {
        return Err(SoldrError::Other(
            "managed LLVM requires the verified v2 catalogue".into(),
        ));
    }
    let entry = index
        .entries
        .iter()
        .find(|entry| {
            entry.owner == "zackees"
                && entry.repo == "clang-tool-chain-bins"
                && entry.tag == "main"
                && entry.asset == asset_name
                && entry.source_path.as_deref() == Some(source_path)
                && entry.min_client_version == Some(2)
                && matches!(entry.transport, AssetTransport::Multipart { ref parts } if !parts.is_empty())
                && entry.matches_legacy_url(asset.url)
        })
        .cloned()
        .ok_or_else(|| {
            SoldrError::Other(format!(
                "LLVM v{MANAGED_LLVM_VERSION} {} is absent from the verified v2 multipart catalogue",
                asset.plat_arch
            ))
        })?;
    if entry.sha256 != asset.sha256 {
        return Err(SoldrError::Other(format!(
            "LLVM catalogue sha256 mismatch for {}: pinned {}, catalogue {}",
            asset.plat_arch, asset.sha256, entry.sha256
        )));
    }
    Ok(entry)
}

/// Marks a `.complete` stamp whose install has had [`restore_bin_exec_bits`]
/// applied.
const STAMP_EXEC_MARKER: &str = "exec-bits";

/// Marks a `.complete` stamp whose `lib/` carries the soldr#3774 host
/// libraries (or whose host needs none).
const STAMP_HOST_LIBS_MARKER: &str = "host-libs";

fn stamp_contents(host_libs: bool) -> String {
    let libs = if host_libs {
        STAMP_HOST_LIBS_MARKER
    } else {
        ""
    };
    format!("{MANAGED_LLVM_VERSION}\n{STAMP_EXEC_MARKER}\n{libs}\n")
}

/// Write the `.complete` stamp by replacing the file, never by rewriting it
/// in place: a host may hardlink identical files across soldr roots
/// (forge-ci/gh-runner#23), and an in-place write would mark every root that
/// shares the inode complete, so those roots would skip their own repair.
fn write_stamp(stamp: &Path, host_libs: bool) -> Result<(), SoldrError> {
    let dir = stamp.parent().unwrap_or_else(|| Path::new("."));
    let mut staged = tempfile::NamedTempFile::new_in(dir)?;
    std::io::Write::write_all(&mut staged, stamp_contents(host_libs).as_bytes())?;
    staged
        .persist(stamp)
        .map_err(|error| SoldrError::Io(error.error))?;
    Ok(())
}

/// soldr#3774: put `libxml2.so.2` / `libz.so.1` beside the bundle's `lld`
/// (`RUNPATH $ORIGIN/../lib`) and prove it no longer needs them from the
/// host. Returns whether the overlay is complete. Hosts without a
/// `llvm-host-libs` row (Windows) need none. A catalogue miss is logged and
/// retried on the next run; hosts that have the libraries keep working
/// meanwhile. A bundle that is still incomplete *after* the overlay is a
/// hard error.
async fn complete_host_libs(paths: &SoldrPaths, bin_dir: &Path) -> Result<bool, SoldrError> {
    let Some(host) = host_triple_for_llvm() else {
        return Ok(true);
    };
    if super::llvm_host_libs::catalogue_slug_for(host).is_none() {
        return Ok(true);
    }
    let root = match super::llvm_host_libs::ensure_llvm_host_libs(paths, host).await {
        Ok(root) => root,
        Err(err) => {
            eprintln!("soldr: managed LLVM host libraries unavailable for {host}: {err}");
            return Ok(false);
        }
    };
    let lib_dir = bin_dir.parent().unwrap_or(bin_dir).join("lib");
    super::llvm_host_libs::install_into(&root, &lib_dir)?;
    super::llvm_host_libs::verify_lld_self_contained(bin_dir)?;
    Ok(true)
}

/// The `linux-arm64` LLVM archive stores its binaries as `rw-rw-rw-` (no
/// exec bit; the x86_64 one is `rwxr-xr-x`), so a clang extracted with the
/// archive's permissions cannot run: the linker shim then fails with
/// `exec: .../hardlinked/bin/clang: Permission denied` (exit 126). Every
/// regular file in `bin/` is a tool, so each gets the executable mode.
/// Hardlinked aliases share the inode and follow.
fn restore_bin_exec_bits(bin_dir: &Path) -> Result<(), SoldrError> {
    for entry in std::fs::read_dir(bin_dir)? {
        let entry = entry?;
        if entry.file_type()?.is_file() {
            crate::platform::fs::permissions::make_executable(&entry.path())?;
        }
    }
    Ok(())
}

fn extract_tar_zst_tree<R: std::io::Read>(reader: R, dest: &Path) -> Result<(), SoldrError> {
    let zst = zstd::stream::read::Decoder::new(reader)
        .map_err(|e| SoldrError::Archive(format!("zstd decoder init: {e}")))?;
    let mut archive = tar::Archive::new(zst);
    archive.set_preserve_permissions(true);
    archive
        .unpack(dest)
        .map_err(|e| SoldrError::Archive(format!("tar.zst unpack: {e}")))?;
    Ok(())
}

